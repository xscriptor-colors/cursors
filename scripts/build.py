#!/usr/bin/env python3
"""Build XCursor themes locally.

Pipeline (no CI involved):
    SVG sources -> PNG bitmaps (rsvg-convert) -> clickgen manifests -> ctgen

Usage:
    python3 scripts/build.py                 # build into build/themes
    python3 scripts/build.py --install       # also copy to ~/.local/share/icons
    python3 scripts/build.py --only x        # single pack
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import art
import spec

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
SIZES = [16, 20, 22, 24, 28, 32, 40, 48, 64, 96]
DELAY_MS = 70

PACKS = {
    "x": {
        "theme": "Xscriptor-X",
        "comment": "Xscriptor X cursors: violet-to-amber gradient, gold rim, X sparks.",
        "website": "https://github.com/xscriptor-colors/cursors",
    },
    "berlin": {
        "theme": "Xscriptor-Berlin",
        "comment": "Xscriptor Berlin cursors: monochrome, white rim, X sparks.",
        "website": "https://github.com/xscriptor-colors/cursors",
    },
}


def render_pack(pack: str) -> Path:
    src_dir = ROOT / "src" / pack
    out_dir = BUILD / "bitmaps" / pack
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    svgs = sorted(src_dir.glob("*.svg"))
    if not svgs:
        raise SystemExit(f"No SVG sources in {src_dir}; run scripts/generate.py")

    def render(svg: Path) -> None:
        png = out_dir / f"{svg.stem}.png"
        subprocess.run(
            ["rsvg-convert", "-w", "256", "-h", "256",
             "-o", str(png), str(svg)],
            check=True,
        )

    with ThreadPoolExecutor() as pool:
        list(pool.map(render, svgs))
    print(f"{pack}: {len(svgs)} PNG frames -> {out_dir}")
    return out_dir


def manifest_text(pack: str) -> str:
    meta = PACKS[pack]
    lines = [
        "# generated by scripts/build.py from scripts/spec.py -- do not edit",
        "[theme]",
        f'name = "{meta["theme"]}"',
        f'comment = "{meta["comment"]}"',
        f'website = "{meta["website"]}"',
        "",
        "[config]",
        f'bitmaps_dir = "../bitmaps/{pack}"',
        'out_dir = "../themes"',
        'platforms = ["x11"]',
        "",
        "[cursors]",
        "",
        "[cursors.fallback_settings]",
        f"x11_sizes = {SIZES}",
        "x_hotspot = 128",
        "y_hotspot = 128",
        f"x11_delay = {DELAY_MS}",
        "",
    ]
    for cursor in spec.CURSORS:
        lines += [
            f'[cursors."{cursor.key}"]',
            f'png = "{cursor.png}"',
            f"x_hotspot = {cursor.hotspot[0]}",
            f"y_hotspot = {cursor.hotspot[1]}",
            f'x11_name = "{cursor.key}"',
        ]
        if cursor.aliases:
            aliases = ", ".join(f'"{a}"' for a in cursor.aliases)
            lines.append(f"x11_symlinks = [{aliases}]")
        lines.append("")
    return "\n".join(lines)


def write_manifest(pack: str) -> Path:
    path = BUILD / "manifests" / f"{pack}.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(manifest_text(pack))
    return path


def run_ctgen(manifest: Path) -> None:
    subprocess.run(["ctgen", str(manifest)], check=True)


def validate(pack: str) -> Path:
    theme = BUILD / "themes" / PACKS[pack]["theme"]
    index = theme / "index.theme"
    cursors = theme / "cursors"
    if not index.is_file() or not cursors.is_dir():
        raise SystemExit(f"Missing generated theme files in {theme}")

    entries = list(cursors.iterdir())
    broken = [p for p in entries if p.is_symlink() and not p.exists()]
    if broken:
        raise SystemExit(f"Broken symlinks in {cursors}: {broken[:5]}")
    print(f"{pack}: {len(entries)} XCursor entries -> {theme}")
    return theme


def install(theme: Path) -> None:
    target = Path.home() / ".local" / "share" / "icons" / theme.name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(theme, target, symlinks=True)
    print(f"installed {target}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", choices=sorted(PACKS), default=None)
    parser.add_argument("--install", action="store_true")
    parser.add_argument("--skip-render", action="store_true")
    args = parser.parse_args()

    packs = [args.only] if args.only else list(PACKS)
    BUILD.mkdir(parents=True, exist_ok=True)

    themes = []
    for pack in packs:
        if not args.skip_render:
            render_pack(pack)
        manifest = write_manifest(pack)
        theme_dir = BUILD / "themes" / PACKS[pack]["theme"]
        if theme_dir.exists():
            shutil.rmtree(theme_dir)
        run_ctgen(manifest)
        themes.append(validate(pack))

    if args.install:
        for theme in themes:
            install(theme)
        print("Preview live: hyprctl setcursor <theme> 24")
    return 0


if __name__ == "__main__":
    sys.exit(main())
